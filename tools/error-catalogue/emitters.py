def fixture_documents(catalogue: Catalogue) -> list[tuple[str, dict[str, object]]]:
    from captures import ALREADY_FIXTURED

    by_stem = captures_by_stem()
    per_code: dict[str, int] = {}
    documents: list[tuple[str, dict[str, object]]] = []

    for rule in catalogue.rules:
        if (rule.kind, rule.text) in ALREADY_FIXTURED:
            continue
        capture = by_stem.get(rule.text)
        status = _fixture_status(rule)

        write = rule.scope_note is not None and "write" in rule.scope_note
        if rule.scope_note is not None and "recordings" in rule.scope_note:
            path = FIXTURE_RECORDINGS_PATH
        else:
            path = FIXTURE_WRITE_PATH if write else FIXTURE_READ_PATH

        requirements = ["ERR-020"]
        if capture is not None:
            requirements.append("ERR-035")

        for message, alternative in _fixture_messages(rule, capture):
            per_code[rule.code] = per_code.get(rule.code, 0) + 1
            identifier = f"errors.recognition.{rule.code.lower()}.{per_code[rule.code]}"
            documents.append(
                (
                    identifier,
                    _fixture_document(
                        catalogue, rule, identifier, status, message, alternative,
                        path, write, requirements, capture,
                    ),
                )
            )

    return documents


def _fixture_document(
    catalogue: Catalogue,
    rule: Rule,
    identifier: str,
    status: int,
    message: str,
    alternative: str | None,
    path: str,
    write: bool,
    requirements: Sequence[str],
    capture: Capture | None,
) -> dict[str, object]:
    """One generated recognition fixture: one rule, one message it must recognise."""
    error: dict[str, object] = {
        "code": rule.code,
        "statusCode": status,
        "retryable": catalogue.by_code()[rule.code].retryable,
        "attempts": 1,
        "serverMessage": message,
    }
    if capture is not None:
        error["detailsKeys"] = list(capture.keys)

    expect_request: dict[str, object] = {
        "method": "POST" if write else "GET",
        "url": f"{FIXTURE_ADDRESS}/v1/{path}",
    }
    operation: dict[str, object] = {
        "name": "Logical.Write" if write else "Logical.Read",
        "args": {"path": path},
    }
    if write:
        operation["args"] = {"path": path, "body": {"policy": "path \"secret/*\" { capabilities = [\"read\"] }"}}
        expect_request["body"] = operation["args"]["body"]  # type: ignore[index]

    qualifier = "" if alternative is None else f" + '{alternative}'"
    return {
        "id": identifier,
        "title": (
            f"Appendix B §2 row {rule.row}: {rule.kind} "
            f"'{rule.text.strip()}'{qualifier} maps to {rule.code}"
        ),
        "capturedFrom": (
            "specifications/appendix-b-error-catalogue.md §2 "
            "(generated by tools/error-catalogue, D-M1c-10)"
        ),
        "requirements": requirements,
        "level": "core",
        "sections": ["04"],
        "client": {
            "address": FIXTURE_ADDRESS,
            "token": FIXTURE_TOKEN,
            "namespace": "",
            "apiPrefix": "v1",
            "settings": {"RateGate": {"RatePerSecond": 0}, "RetryPolicy": {"MaxAttempts": 1}},
        },
        "operation": operation,
        "exchanges": [
            {
                "expectRequest": expect_request,
                "respond": {"status": status, "body": {"error": message}},
            }
        ],
        "expect": {"error": error},
    }


def check_first_match(catalogue: Catalogue, documents: Sequence[tuple[str, dict[str, object]]]) -> None:
    """Every generated fixture must be won by the rule it was generated from.

    First-match-wins (D-M1c-3) means a later row can be shadowed by an earlier
    one. Rather than trust the reading, the generator replays its own matcher
    over every fixture it emits and fails if the winning rule names a different
    code.
    """
    from catalogue import CatalogueError, normalise

    for identifier, document in documents:
        exchange = document["exchanges"][0]  # type: ignore[index]
        status = exchange["respond"]["status"]  # type: ignore[index]
        message = exchange["respond"]["body"]["error"]  # type: ignore[index]
        expected = document["expect"]["error"]["code"]  # type: ignore[index]
        normalised = normalise(message)
        path = str(document["operation"]["args"]["path"])  # type: ignore[index]
        winner = next((rule for rule in catalogue.rules if matches(rule, normalised, status, path)), None)
        if winner is None:
            raise CatalogueError(f"generated fixture {identifier} matches no recognition rule")
        if winner.code != expected:
            raise CatalogueError(
                f"generated fixture {identifier} expects {expected} but first-match-wins "
                f"(D-M1c-3) awards it to row {winner.row} → {winner.code}"
            )
        fallback = STATUS_FALLBACK_CODE.get(status)
        if fallback is not None and fallback == expected:
            raise CatalogueError(
                f"generated fixture {identifier} would pass on the status table alone"
            )


def emit_fixtures(catalogue: Catalogue) -> dict[str, str]:
    documents = fixture_documents(catalogue)
    check_first_match(catalogue, documents)
    return {
        f"{FIXTURE_DIR}/{identifier}.json": json.dumps(document, indent=2, ensure_ascii=False) + "\n"
        for identifier, document in documents
    }


