def emit_intermediate(catalogue: Catalogue) -> str:
    from captures import DETAILS_CAPTURES

    payload = {
        "generatedFrom": "specifications/appendix-b-error-catalogue.md",
        "generator": "tools/error-catalogue",
        "codes": [entry.as_json() for entry in catalogue.codes],
        "recognition": [rule.as_json() for rule in catalogue.rules],
        "detailsCaptures": [capture.as_json() for capture in DETAILS_CAPTURES],
    }
    return json.dumps(payload, indent=2, ensure_ascii=False) + "\n"


def artefacts(catalogue: Catalogue) -> dict[str, str]:
    """Every file the generator owns, keyed by repository-relative path."""
    files: dict[str, str] = {
        "tools/error-catalogue/catalogue.json": emit_intermediate(catalogue),
        DOTNET_PATH: emit_dotnet(catalogue),
        RUST_PATH: emit_rust(catalogue),
        PYTHON_PATH: emit_python(catalogue),
        "rust/bastionvault-integration-sdk/src/generated/mod.rs": RUST_MOD,
        "python/src/bastionvault_integration_sdk/_generated/__init__.py": PYTHON_INIT,
    }
    files.update(emit_fixtures(catalogue))
    return files


def owned_fixture_paths(root: Path) -> set[Path]:
    """Generated fixture files currently on disk, so a deleted row's file is removed."""
    directory = root / FIXTURE_DIR
    if not directory.is_dir():
        return set()
    return {
        path
        for path in directory.glob("errors.recognition.bv-*.json")
        if path.is_file()
    }


