def _cs(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _xml(text: str) -> str:
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def _rs(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _py_wrapped(text: str, indent: int, limit: int = 108) -> list[str]:
    """A Python string literal wrapped with implicit concatenation.

    `ruff`'s E501 applies to generated sources as much as to hand-written ones
    (CNF-023, and CLA-004 forbids exempting a path to make a gate pass), so long
    catalogue hints are split on spaces rather than emitted on one long line.
    """
    pad = " " * indent
    escaped_words = text.split(" ")
    lines: list[str] = []
    current = ""
    for index, word in enumerate(escaped_words):
        candidate = word if not current else current + " " + word
        # +3 for the two quotes and a trailing space marker.
        if current and len(pad) + len(json.dumps(candidate + " ")) > limit:
            lines.append(pad + json.dumps(current + " "))
            current = word
        else:
            current = candidate
        del index
    lines.append(pad + json.dumps(current))
    return lines


def _fixture_status(rule: Rule) -> int:
    if rule.guard is not None:
        if rule.guard.status is not None:
            return rule.guard.status
        if rule.guard.status_class is not None:
            return rule.guard.status_class * 100
    if rule.code == STATUS_FALLBACK_CODE[DEFAULT_FIXTURE_STATUS]:
        return ALTERNATE_FIXTURE_STATUS
    return DEFAULT_FIXTURE_STATUS


def _fixture_message(rule: Rule, capture: Capture | None) -> str:
    return _fixture_messages(rule, capture)[0][0]


def _fixture_messages(rule: Rule, capture: Capture | None) -> list[tuple[str, str | None]]:
    """The ``(message, alternative)`` pairs one rule's generated fixtures drive.

    A rule with a qualifier group gets **one fixture per alternative** (D-M8-3).
    A single fixture carrying every alternative at once would pass under the
    conjunctive reading of Appendix B §2 as well as the alternation the appendix
    means, so it would certify R-23's defect instead of catching it.
    """
    if capture is not None:
        return [(capture.sample, None)]
    stem = [rule.text.strip()]
    stem += [item.strip() for item in rule.contains_all]
    if not rule.contains_any:
        return [(" ".join(part for part in stem if part), None)]
    return [
        (" ".join(part for part in stem + [alternative.strip()] if part), alternative.strip())
        for alternative in rule.contains_any
    ]


def login_rejections(catalogue: Catalogue) -> list[tuple[str, str]]:
    """D-M2-25 item 3: the ``(message, code)`` rows a 200 login rejection can carry.

    Derived from the same parsed Appendix B §2 table the recogniser is generated
    from, restricted to :data:`LOGIN_REJECTION_CODES` and to rows a status of
    ``200`` can actually reach.  Each language's mock server parameterises its
    ``login-failure-as-200`` simulation from this list instead of a hand-written
    string, so a fixture can never assert a ``data.error`` message the mock
    cannot produce.
    """
    by_stem = captures_by_stem()
    rows: list[tuple[str, str]] = []
    for rule in catalogue.rules:
        if rule.code not in LOGIN_REJECTION_CODES:
            continue
        if rule.path_contains is not None:
            continue
        if rule.guard is not None and not (
            (rule.guard.status is None or rule.guard.status == 200)
            and (rule.guard.status_class is None or rule.guard.status_class == 2)
        ):
            continue
        message = _fixture_message(rule, by_stem.get(rule.text))
        if not matches(rule, normalise(message), 200):
            # A row whose own sample message does not recognise back to it from a
            # 200 would let the mock produce a body the SDK maps elsewhere. The
            # generator refuses to emit it rather than shipping the mismatch.
            raise CatalogueError(
                f"Appendix B §2 row {rule.row} ({rule.code}) is listed as a 200 login "
                f"rejection but its message {message!r} does not recognise to it at status 200."
            )
        rows.append((message, rule.code))

    missing = sorted(set(LOGIN_REJECTION_CODES) - {code for _, code in rows})
    if missing:
        raise CatalogueError(
            "AUT-011 names these 200-login-rejection codes but Appendix B §2 has no "
            f"reachable row producing them: {', '.join(missing)}"
        )
    return rows


def matches(rule: Rule, normalised: str, status: int, path: str = "") -> bool:
    """The runtime matcher, in Python, used by the generator's own self-check."""
    if rule.path_contains is not None and rule.path_contains not in path:
        return False
    if rule.guard is not None:
        if rule.guard.status is not None and status != rule.guard.status:
            return False
        if rule.guard.status_class is not None and status // 100 != rule.guard.status_class:
            return False
    if rule.kind == "exact":
        if normalised != rule.text.strip():
            return False
    elif rule.kind == "prefix":
        if not normalised.startswith(rule.text):
            return False
    else:
        if rule.text.strip() not in normalised:
            return False
    # A qualifier group is ANDed with the stem, but its items are alternatives
    # (D-M8-2): an empty group imposes nothing, a non-empty one needs one hit.
    return all(item.strip() in normalised for item in rule.contains_all) and (
        not rule.contains_any
        or any(item.strip() in normalised for item in rule.contains_any)
    )


