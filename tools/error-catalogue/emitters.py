def emit_dotnet(catalogue: Catalogue) -> str:
    by_stem = captures_by_stem()
    captures = list(by_stem.values())
    capture_index = {capture.stem: index for index, capture in enumerate(captures)}

    out: list[str] = ["// <auto-generated>"]
    out += [f"//     {line}" for line in BANNER_LINES]
    out += ["// </auto-generated>", "", "namespace BastionVault.IntegrationSdk", "{"]
    out += ["    public static partial class ErrorCodes", "    {"]
    for index, entry in enumerate(catalogue.codes):
        if index:
            out.append("")
        out.append(f"        /// <summary>{_xml(entry.message)}</summary>")
        out.append(f"        public const string {entry.constant} = {_cs(entry.code)};")
    out += ["    }", "}", "", "namespace BastionVault.IntegrationSdk.Internal", "{"]
    out += [
        "    internal static class ErrorCatalogData",
        "    {",
        "        /// <summary>Appendix B §1, in appendix order (ERR-036, D-M1c-7's <c>All</c>).</summary>",
        "        internal static readonly ErrorCatalogEntry[] Entries =",
        "        [",
    ]
    for entry in catalogue.codes:
        out.append(
            "            new("
            + f"{_cs(entry.code)}, {_cs(entry.name)}, ErrorCategory.{entry.category},"
        )
        out.append(f"                {_cs(entry.message)},")
        out.append(f"                {_cs(entry.hint)},")
        out.append(f"                {str(entry.retryable).lower()}),")
    out += ["        ];", ""]

    out += [
        "        /// <summary>Appendix B §2, in table order — first match wins (D-M1c-3).</summary>",
        "        internal static readonly RecognitionRule[] Rules =",
        "        [",
    ]
    for rule in catalogue.rules:
        contains = ", ".join(_cs(item) for item in rule.contains_all)
        contains_literal = f"[{contains}]" if contains else "[]"
        any_of = ", ".join(_cs(item) for item in rule.contains_any)
        any_literal = f"[{any_of}]" if any_of else "[]"
        status = "null" if rule.guard is None or rule.guard.status is None else str(rule.guard.status)
        klass = (
            "null"
            if rule.guard is None or rule.guard.status_class is None
            else str(rule.guard.status_class)
        )
        index = capture_index.get(rule.text, -1)
        scope = "null" if rule.path_contains is None else _cs(rule.path_contains)
        out.append(
            f"            new(RecognitionKind.{rule.kind.capitalize()}, {_cs(rule.text)}, {contains_literal},"
        )
        out.append(
            f"                {any_literal}, {status}, {klass}, {scope}, {_cs(rule.code)}, {index}),"
        )
    out += ["        ];", ""]

    out += [
        "        /// <summary>The D-M1c-4 capture table, hand-authored in the generator's input.</summary>",
        "        internal static readonly DetailsCapture[] Captures =",
        "        [",
    ]
    for capture in captures:
        keys = ", ".join(_cs(key) for key in capture.keys)
        out.append(
            f"            new(DetailsCaptureKind.{_pascal(capture.kind)}, [{keys}],"
            f" {_cs(capture.prefix)}, {_cs(capture.suffix)}),"
        )
    out += ["        ];", ""]

    out += [
        "        /// <summary>",
        "        /// D-M2-25 item 3: the <c>data.error</c> messages a <c>200</c> login rejection can carry",
        "        /// (AUT-011), each with the code the generated <see cref=\"Rules\"/> table maps it to. Read by",
        "        /// the test harness's mock server so its <c>login-failure-as-200</c> simulation (TST-021)",
        "        /// cannot drift from the recogniser, and by the AUT-011 tests so every row is exercised.",
        "        /// </summary>",
        "        internal static readonly LoginRejection[] LoginRejections =",
        "        [",
    ]
    for message, code in login_rejections(catalogue):
        out.append(f"            new({_cs(code)}, {_cs(message)}),")
    out += ["        ];", "    }", "}", ""]
    return "\n".join(out)


def _pascal(snake: str) -> str:
    return "".join(part.capitalize() for part in snake.split("_"))


